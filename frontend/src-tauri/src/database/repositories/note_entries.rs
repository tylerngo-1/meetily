//! Note entries taken during or after a meeting: typed notes, bookmarks and agenda items.
//!
//! Entries are anchored to the recording clock (`start_ms` / `end_ms`, see
//! `RecordingState::get_recording_offset_ms`), never to transcript rows. Re-transcription
//! replaces every transcript row, so nothing in this table references `transcripts`.

use chrono::Utc;
use serde::{Deserialize, Serialize};
use sqlx::{Connection, SqlitePool};

pub const MAX_TEXT_CHARS: usize = 5_000;
pub const MAX_QUOTED_TEXT_CHARS: usize = 500;
pub const MAX_ENTRIES_PER_MEETING: usize = 1_000;

const KINDS: [&str; 3] = ["note", "bookmark", "agenda"];
const TAGS: [&str; 3] = ["action", "decision", "question"];

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, sqlx::FromRow)]
#[serde(rename_all = "camelCase")]
pub struct NoteEntry {
    pub id: String,
    pub meeting_id: String,
    pub kind: String,
    pub tag: Option<String>,
    pub text: String,
    pub start_ms: Option<i64>,
    pub end_ms: Option<i64>,
    pub quoted_text: Option<String>,
    pub done: bool,
    pub position: i64,
    pub created_at: String,
    pub updated_at: String,
}

/// What the UI sends. Ids are generated by the UI so entries keep their identity from the
/// in-memory draft (during recording) to the database (after stop).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NoteEntryInput {
    pub id: String,
    pub kind: String,
    pub tag: Option<String>,
    #[serde(default)]
    pub text: String,
    pub start_ms: Option<i64>,
    pub end_ms: Option<i64>,
    pub quoted_text: Option<String>,
    #[serde(default)]
    pub done: bool,
    pub position: i64,
}

impl NoteEntryInput {
    /// Checks the entry and normalizes it: trims the id, empties a blank tag and truncates
    /// `quoted_text` (it is a convenience copy of transcript text, so it is cut, not rejected).
    pub fn validate(mut self) -> Result<Self, String> {
        self.id = self.id.trim().to_string();
        if self.id.is_empty() {
            return Err("Note entry id cannot be empty".to_string());
        }
        if !KINDS.contains(&self.kind.as_str()) {
            return Err(format!("Unknown note entry kind: {}", self.kind));
        }
        if let Some(tag) = &self.tag {
            if tag.trim().is_empty() {
                self.tag = None;
            } else if !TAGS.contains(&tag.as_str()) {
                return Err(format!("Unknown note tag: {}", tag));
            }
        }
        if self.text.chars().count() > MAX_TEXT_CHARS {
            return Err(format!(
                "A note can be at most {} characters long",
                MAX_TEXT_CHARS
            ));
        }
        if self.start_ms.is_some_and(|ms| ms < 0) || self.end_ms.is_some_and(|ms| ms < 0) {
            return Err("Note times cannot be negative".to_string());
        }
        if let (Some(start), Some(end)) = (self.start_ms, self.end_ms) {
            if end < start {
                return Err("A note cannot end before it starts".to_string());
            }
        }
        if let Some(quoted) = &self.quoted_text {
            if quoted.chars().count() > MAX_QUOTED_TEXT_CHARS {
                self.quoted_text = Some(quoted.chars().take(MAX_QUOTED_TEXT_CHARS).collect());
            }
        }
        Ok(self)
    }
}

pub struct NoteEntriesRepository;

impl NoteEntriesRepository {
    pub async fn list_entries(
        pool: &SqlitePool,
        meeting_id: &str,
    ) -> Result<Vec<NoteEntry>, sqlx::Error> {
        sqlx::query_as::<_, NoteEntry>(
            "SELECT id, meeting_id, kind, tag, text, start_ms, end_ms, quoted_text, done,
                    position, created_at, updated_at
             FROM meeting_note_entries
             WHERE meeting_id = ?
             ORDER BY position, created_at",
        )
        .bind(meeting_id)
        .fetch_all(pool)
        .await
    }

    /// Replaces every entry of a meeting in one transaction. Used once, when the draft taken
    /// during recording is saved after stop. Returns `Ok(false)` if the meeting does not exist.
    pub async fn replace_entries(
        pool: &SqlitePool,
        meeting_id: &str,
        entries: Vec<NoteEntryInput>,
    ) -> Result<bool, String> {
        if entries.len() > MAX_ENTRIES_PER_MEETING {
            return Err(format!(
                "A meeting can have at most {} notes",
                MAX_ENTRIES_PER_MEETING
            ));
        }
        let entries = entries
            .into_iter()
            .map(NoteEntryInput::validate)
            .collect::<Result<Vec<_>, _>>()?;

        let db = |e: sqlx::Error| format!("Failed to save notes: {}", e);
        let mut conn = pool.acquire().await.map_err(db)?;
        let mut tx = conn.begin().await.map_err(db)?;

        let exists: Option<(i64,)> = sqlx::query_as("SELECT 1 FROM meetings WHERE id = ?")
            .bind(meeting_id)
            .fetch_optional(&mut *tx)
            .await
            .map_err(db)?;
        if exists.is_none() {
            return Ok(false);
        }

        sqlx::query("DELETE FROM meeting_note_entries WHERE meeting_id = ?")
            .bind(meeting_id)
            .execute(&mut *tx)
            .await
            .map_err(db)?;

        let now = Utc::now().to_rfc3339();
        for entry in &entries {
            insert_or_update(&mut *tx, meeting_id, entry, &now)
                .await
                .map_err(db)?;
        }

        tx.commit().await.map_err(db)?;
        Ok(true)
    }

    /// Inserts or updates one entry. An existing entry keeps its `created_at` and can never
    /// move to another meeting. Returns `Ok(None)` if the meeting does not exist or the id
    /// belongs to another meeting.
    pub async fn upsert_entry(
        pool: &SqlitePool,
        meeting_id: &str,
        entry: NoteEntryInput,
    ) -> Result<Option<NoteEntry>, String> {
        let entry = entry.validate()?;
        let db = |e: sqlx::Error| format!("Failed to save note: {}", e);

        let exists: Option<(i64,)> = sqlx::query_as("SELECT 1 FROM meetings WHERE id = ?")
            .bind(meeting_id)
            .fetch_optional(pool)
            .await
            .map_err(db)?;
        if exists.is_none() {
            return Ok(None);
        }

        let now = Utc::now().to_rfc3339();
        let affected = insert_or_update(pool, meeting_id, &entry, &now)
            .await
            .map_err(db)?;
        if affected == 0 {
            return Ok(None);
        }

        sqlx::query_as::<_, NoteEntry>(
            "SELECT id, meeting_id, kind, tag, text, start_ms, end_ms, quoted_text, done,
                    position, created_at, updated_at
             FROM meeting_note_entries WHERE id = ?",
        )
        .bind(&entry.id)
        .fetch_optional(pool)
        .await
        .map_err(db)
    }

    /// Deletes one entry of a meeting. Returns whether a row was deleted.
    pub async fn delete_entry(
        pool: &SqlitePool,
        meeting_id: &str,
        entry_id: &str,
    ) -> Result<bool, sqlx::Error> {
        let result =
            sqlx::query("DELETE FROM meeting_note_entries WHERE id = ? AND meeting_id = ?")
                .bind(entry_id)
                .bind(meeting_id)
                .execute(pool)
                .await?;
        Ok(result.rows_affected() > 0)
    }
}

/// Returns the number of affected rows: 0 when the id already exists under another meeting.
async fn insert_or_update<'e, E>(
    executor: E,
    meeting_id: &str,
    entry: &NoteEntryInput,
    now: &str,
) -> Result<u64, sqlx::Error>
where
    E: sqlx::Executor<'e, Database = sqlx::Sqlite>,
{
    let result = sqlx::query(
        "INSERT INTO meeting_note_entries
            (id, meeting_id, kind, tag, text, start_ms, end_ms, quoted_text, done, position,
             created_at, updated_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
         ON CONFLICT(id) DO UPDATE SET
            kind = excluded.kind,
            tag = excluded.tag,
            text = excluded.text,
            start_ms = excluded.start_ms,
            end_ms = excluded.end_ms,
            quoted_text = excluded.quoted_text,
            done = excluded.done,
            position = excluded.position,
            updated_at = excluded.updated_at
         WHERE meeting_note_entries.meeting_id = excluded.meeting_id",
    )
    .bind(&entry.id)
    .bind(meeting_id)
    .bind(&entry.kind)
    .bind(&entry.tag)
    .bind(&entry.text)
    .bind(entry.start_ms)
    .bind(entry.end_ms)
    .bind(&entry.quoted_text)
    .bind(entry.done)
    .bind(entry.position)
    .bind(now)
    .bind(now)
    .execute(executor)
    .await?;
    Ok(result.rows_affected())
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use sqlx::sqlite::SqlitePoolOptions;

    /// In-memory database with every real migration applied. One connection, because each
    /// connection to `sqlite::memory:` is a separate database.
    pub(crate) async fn migrated_pool() -> SqlitePool {
        let pool = SqlitePoolOptions::new()
            .max_connections(1)
            .connect("sqlite::memory:")
            .await
            .unwrap();
        sqlx::migrate!("./migrations").run(&pool).await.unwrap();
        pool
    }

    pub(crate) async fn insert_meeting(pool: &SqlitePool, id: &str) {
        let now = Utc::now();
        sqlx::query("INSERT INTO meetings (id, title, created_at, updated_at) VALUES (?, ?, ?, ?)")
            .bind(id)
            .bind("Test meeting")
            .bind(now)
            .bind(now)
            .execute(pool)
            .await
            .unwrap();
    }

    pub(crate) fn entry(id: &str, kind: &str, position: i64) -> NoteEntryInput {
        NoteEntryInput {
            id: id.to_string(),
            kind: kind.to_string(),
            tag: None,
            text: format!("text {}", id),
            start_ms: Some(position * 1_000),
            end_ms: Some(position * 1_000 + 500),
            quoted_text: None,
            done: false,
            position,
        }
    }

    #[test]
    fn validate_rejects_bad_input() {
        assert!(entry(" ", "note", 0).validate().is_err());
        assert!(entry("a", "comment", 0).validate().is_err());
        assert!(NoteEntryInput { tag: Some("todo".into()), ..entry("a", "note", 0) }
            .validate()
            .is_err());
        assert!(NoteEntryInput { start_ms: Some(-1), ..entry("a", "note", 0) }
            .validate()
            .is_err());
        assert!(NoteEntryInput { start_ms: Some(10), end_ms: Some(5), ..entry("a", "note", 0) }
            .validate()
            .is_err());
        assert!(NoteEntryInput { text: "x".repeat(MAX_TEXT_CHARS + 1), ..entry("a", "note", 0) }
            .validate()
            .is_err());
    }

    #[test]
    fn validate_normalizes_tag_and_quote() {
        let e = NoteEntryInput {
            tag: Some(" ".into()),
            quoted_text: Some("ạ".repeat(MAX_QUOTED_TEXT_CHARS + 10)),
            ..entry("a", "note", 0)
        }
        .validate()
        .unwrap();
        assert_eq!(e.tag, None);
        assert_eq!(e.quoted_text.unwrap().chars().count(), MAX_QUOTED_TEXT_CHARS);
    }

    #[tokio::test]
    async fn replace_then_list_keeps_order_and_fields() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;

        let tagged = NoteEntryInput {
            tag: Some("action".into()),
            quoted_text: Some("An will do the backend".into()),
            ..entry("b", "bookmark", 1)
        };
        let saved = NoteEntriesRepository::replace_entries(
            &pool,
            "m1",
            vec![tagged, entry("a", "note", 0), entry("c", "agenda", 2)],
        )
        .await
        .unwrap();
        assert!(saved);

        let listed = NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap();
        let ids: Vec<_> = listed.iter().map(|e| e.id.as_str()).collect();
        assert_eq!(ids, ["a", "b", "c"]);
        assert_eq!(listed[1].tag.as_deref(), Some("action"));
        assert_eq!(listed[1].start_ms, Some(1_000));
        assert_eq!(listed[1].quoted_text.as_deref(), Some("An will do the backend"));

        // Replacing again drops entries that are no longer in the draft.
        NoteEntriesRepository::replace_entries(&pool, "m1", vec![entry("a", "note", 0)])
            .await
            .unwrap();
        assert_eq!(NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap().len(), 1);
    }

    #[tokio::test]
    async fn replace_for_unknown_meeting_saves_nothing() {
        let pool = migrated_pool().await;
        let saved = NoteEntriesRepository::replace_entries(&pool, "missing", vec![entry("a", "note", 0)])
            .await
            .unwrap();
        assert!(!saved);
    }

    #[tokio::test]
    async fn replace_rejects_the_whole_batch_on_one_bad_entry() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;
        NoteEntriesRepository::replace_entries(&pool, "m1", vec![entry("a", "note", 0)])
            .await
            .unwrap();

        let result = NoteEntriesRepository::replace_entries(
            &pool,
            "m1",
            vec![entry("b", "note", 0), entry("c", "comment", 1)],
        )
        .await;
        assert!(result.is_err());
        let ids: Vec<_> = NoteEntriesRepository::list_entries(&pool, "m1")
            .await
            .unwrap()
            .into_iter()
            .map(|e| e.id)
            .collect();
        assert_eq!(ids, ["a"]);
    }

    #[tokio::test]
    async fn upsert_updates_in_place_and_keeps_created_at() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;

        let first = NoteEntriesRepository::upsert_entry(&pool, "m1", entry("a", "note", 0))
            .await
            .unwrap()
            .unwrap();
        let updated = NoteEntriesRepository::upsert_entry(
            &pool,
            "m1",
            NoteEntryInput { text: "edited".into(), done: true, ..entry("a", "note", 0) },
        )
        .await
        .unwrap()
        .unwrap();

        assert_eq!(updated.text, "edited");
        assert!(updated.done);
        assert_eq!(updated.created_at, first.created_at);
        assert_eq!(NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap().len(), 1);
    }

    #[tokio::test]
    async fn upsert_cannot_move_an_entry_to_another_meeting() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;
        insert_meeting(&pool, "m2").await;
        NoteEntriesRepository::upsert_entry(&pool, "m1", entry("a", "note", 0))
            .await
            .unwrap();

        let moved = NoteEntriesRepository::upsert_entry(&pool, "m2", entry("a", "note", 0))
            .await
            .unwrap();
        assert!(moved.is_none());
        assert_eq!(NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap().len(), 1);
        assert!(NoteEntriesRepository::list_entries(&pool, "m2").await.unwrap().is_empty());
    }

    #[tokio::test]
    async fn delete_is_scoped_to_the_meeting() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;
        NoteEntriesRepository::upsert_entry(&pool, "m1", entry("a", "note", 0))
            .await
            .unwrap();

        assert!(!NoteEntriesRepository::delete_entry(&pool, "m2", "a").await.unwrap());
        assert!(NoteEntriesRepository::delete_entry(&pool, "m1", "a").await.unwrap());
        assert!(NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap().is_empty());
    }

    #[tokio::test]
    async fn deleting_a_meeting_removes_its_entries_and_participants() {
        use crate::database::repositories::meeting::MeetingsRepository;
        use crate::database::repositories::meeting_prep::MeetingPrepRepository;

        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;
        NoteEntriesRepository::replace_entries(&pool, "m1", vec![entry("a", "note", 0)])
            .await
            .unwrap();
        MeetingPrepRepository::set_participants(&pool, "m1", vec!["An".into()])
            .await
            .unwrap();

        assert!(MeetingsRepository::delete_meeting(&pool, "m1").await.unwrap());

        let count = |table: &'static str| {
            let pool = pool.clone();
            async move {
                let (n,): (i64,) = sqlx::query_as(&format!("SELECT COUNT(*) FROM {}", table))
                    .fetch_one(&pool)
                    .await
                    .unwrap();
                n
            }
        };
        assert_eq!(count("meeting_note_entries").await, 0);
        assert_eq!(count("meeting_participants").await, 0);
        // People are kept for autocomplete.
        assert_eq!(count("people").await, 1);
    }

    /// Re-transcription deletes and re-inserts every transcript row of a meeting
    /// (`audio/retranscription.rs`). Notes must not be affected.
    #[tokio::test]
    async fn entries_survive_transcript_replacement() {
        let pool = migrated_pool().await;
        insert_meeting(&pool, "m1").await;
        let insert_transcript = |id: &'static str, start: f64| {
            let pool = pool.clone();
            async move {
                sqlx::query(
                    "INSERT INTO transcripts (id, meeting_id, transcript, timestamp, audio_start_time, audio_end_time, duration)
                     VALUES (?, 'm1', 'text', '00:00', ?, ?, 1.0)",
                )
                .bind(id)
                .bind(start)
                .bind(start + 1.0)
                .execute(&pool)
                .await
                .unwrap();
            }
        };
        insert_transcript("t1", 0.0).await;
        insert_transcript("t2", 1.0).await;
        NoteEntriesRepository::replace_entries(
            &pool,
            "m1",
            vec![entry("a", "note", 0), entry("b", "bookmark", 1)],
        )
        .await
        .unwrap();
        let before = NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap();

        // Same statements as the re-transcription save path.
        sqlx::query("DELETE FROM transcripts WHERE meeting_id = ?")
            .bind("m1")
            .execute(&pool)
            .await
            .unwrap();
        insert_transcript("t3", 0.2).await;

        let after = NoteEntriesRepository::list_entries(&pool, "m1").await.unwrap();
        assert_eq!(before, after);
    }
}
